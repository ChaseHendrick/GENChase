class Missing(RuntimeError):
    pass


def one(pat, text, flags=0):
    ms = list(re.finditer(pat, text, flags))
    if len(ms) != 1:
        raise Missing('pattern %r matched %d times' % (pat, len(ms)))
    return ms[0]


def every(pat, text, n, flags=0):
    ms = list(re.finditer(pat, text, flags))
    if len(ms) != n:
        raise Missing('pattern %r matched %d times, expected %d' % (pat, len(ms), n))
    return ms


def block(text, start, end):
    """The text between the unique occurrence of start and the next occurrence of end."""
    i = text.index(start)
    if text.count(start) != 1:
        raise Missing('block start %r is not unique' % start)
    j = text.index(end, i + len(start)) if end else len(text)
    return text[i:j]


# ------------------------------------------------------------------ exact outward formatting
def ball_iv(m, r):
    return Fr(m) - Fr(r), Fr(m) + Fr(r)


def _fixed(q, d, up):
    n = math.ceil(q * 10 ** d) if up else math.floor(q * 10 ** d)
    sign = '-' if n < 0 else ''
    n = abs(n)
    ip, fp = divmod(n, 10 ** d)
    return sign + str(ip) + (('.' + str(fp).zfill(d)) if d > 0 else '')


def lo(q, d):
    return _fixed(Fr(q), d, False)


def hi(q, d):
    return _fixed(Fr(q), d, True)


def iv(a, b, d):
    """'[a, b]' rounded outward to d decimals, as TeX."""
    return '[%s, %s]' % (tex(lo(a, d)), tex(hi(b, d)))


def sci_up(q, sig=2):
    """An upper bound of q > 0 as TeX scientific notation with sig significant digits, rounded up."""
    q = Fr(q)
    E = math.floor(math.log10(float(q)))
    while Fr(10) ** E > q:
        E -= 1
    while Fr(10) ** (E + 1) <= q:
        E += 1
    n = math.ceil(q / Fr(10) ** (E - sig + 1))
    if n >= 10 ** sig:
        E += 1
        n = math.ceil(q / Fr(10) ** (E - sig + 1))
    ds = str(n)
    mant = ds[0] + (('.' + ds[1:]) if len(ds) > 1 else '')
    return '%s\\cdot 10^{%d}' % (mant, E)


def tex(s):
    """A decimal string as TeX (the minus sign stays a hyphen-minus; TeX math makes it a minus)."""
    return s


def sci_tex(s):
    """'2.25e-09' -> '2.25\\cdot 10^{-9}'."""
    m = re.fullmatch(r'(-?[0-9.]+)e([+-]?)0*([0-9]+)', s)
    if not m:
        return s
    return '%s\\cdot 10^{%s%s}' % (m.group(1), '-' if m.group(2) == '-' else '', m.group(3))


