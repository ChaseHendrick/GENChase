"""Write the numbers and table rows of the manuscript from the two certificate reports.

    python3 code/hh_make_numbers.py          (from the paper's folder, or from anywhere)

Every number of the manuscript that a program prints is taken from data/certify_equilibria_hopf.txt,
data/certify_bistability.txt, data/identify_stable_orbit.txt, data/numerics_h2.txt or data/mutation_study.txt here,
never typed by hand.  The rules:

  * an Arb ball printed as [m +/- r] is read as the exact rational interval [m - r, m + r] (Arb prints a decimal
    ball that contains its ball), and every interval is re-rounded OUTWARD to the number of decimals shown: the
    lower end down, the upper end up, in exact rational arithmetic (fractions.Fraction), never through a float;
  * an interval [lo, hi] or a bound <= x / >= x that a program already rounded outward is copied, or re-rounded
    outward to fewer digits;
  * a number printed by a non-rigorous stage (numerics, the high-precision refinement) is copied as printed and is
    used only where the manuscript labels it numerical;
  * every pattern must match exactly once (or the stated number of times), and the reports must say that every
    check passed; otherwise this program stops, and nothing is written.

The macros and the rows of the generated tables (the unstable branch, the orbits of Theorem 5, the SHA-256 digests of the
programs and reports) go into one marked block of paper/hh-dynamics.tex, between
the lines "% BEGIN generated by code/hh_make_numbers.py" and "% END generated by code/hh_make_numbers.py", which this program
replaces; the manuscript is then one self-contained file, as tools/paper-build.sh expects.
"""
